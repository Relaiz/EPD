        public void CreateEvent(Event ev)
        {
            if (ev.IsAutoGenerated)
            {
                using var dbContext = new AppDbContext();
                dbContext.Events.Add(ev);
                dbContext.SaveChanges();
                return;
            }
            DateTime parentDate = ev.StartTime.Date;
            while (parentDate <= ev.EndTime.Date && (parentDate.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday || HolidayHelper.IsCzechHoliday(parentDate)))
            {
                parentDate = parentDate.AddDays(1);
            }
            if (parentDate > ev.EndTime.Date)
                return;

            using var db = new AppDbContext();

            var parent = new Event
            {
                Title = ev.Title,
                Description = ev.Description,
                EventType = ev.EventType,
                AllDay = ev.AllDay,
                StartTime = parentDate + ev.StartTime.TimeOfDay,
                EndTime = parentDate + ev.EndTime.TimeOfDay,
                ArrivalTime = parentDate + ev.ArrivalTime.TimeOfDay,
                DepartureTime = parentDate + ev.DepartureTime.TimeOfDay,
                LunchStart = parentDate + ev.LunchStart.TimeOfDay,
                LunchEnd = parentDate + ev.LunchEnd.TimeOfDay,
                ParentEventId = null,
                IsAutoGenerated = ev.IsAutoGenerated,
                ImportBatchId = ev.ImportBatchId,
                ImportLabel = ev.ImportLabel

            };
            db.Events.Add(parent);
            db.SaveChanges();

            for (var day = parentDate.AddDays(1); day <= ev.EndTime.Date; day = day.AddDays(1))
            {
                if (day.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday || HolidayHelper.IsCzechHoliday(day))
                    continue;

                var child = new Event
                {
                    Title = ev.Title,
                    Description = ev.Description,
                    EventType = ev.EventType,
                    AllDay = ev.AllDay,
                    StartTime = day + ev.StartTime.TimeOfDay,
                    EndTime = day + ev.EndTime.TimeOfDay,
                    ArrivalTime = day + ev.ArrivalTime.TimeOfDay,
                    DepartureTime = day + ev.DepartureTime.TimeOfDay,
                    LunchStart = day + ev.LunchStart.TimeOfDay,
                    LunchEnd = day + ev.LunchEnd.TimeOfDay,
                    ParentEventId = parent.Id,
                    IsAutoGenerated = ev.IsAutoGenerated,
                    ImportBatchId = ev.ImportBatchId,
                    ImportLabel = ev.ImportLabel
                };
                db.Events.Add(child);
            }
            db.SaveChanges();

            var affectedDates = Enumerable
                .Range(0, (ev.EndTime.Date - parentDate).Days + 1)
                .Select(offset => parentDate.AddDays(offset))
                .Where(d => d.DayOfWeek is not DayOfWeek.Saturday and not DayOfWeek.Sunday
                         && !HolidayHelper.IsCzechHoliday(d))
                .ToList();

            var autos = db.Events
                .Where(x => x.IsAutoGenerated
                         && x.AutoGeneratedForDate.HasValue
                         && affectedDates.Contains(x.AutoGeneratedForDate.Value.Date))
                .ToList();
            db.Events.RemoveRange(autos);
            db.SaveChanges();

            var sem = GlobalSettingsService.GetSemesterForDate(parentDate);
            var glob = GlobalSettingsService.LoadGlobalSettings(parentDate.Year, sem)
                        ?? GlobalSettingsService.GetDefaultSettings(parentDate.Year, sem);
            var gStart = TimeSpan.Parse(glob.GlobalStartTime);
            var gEnd = TimeSpan.Parse(glob.GlobalEndTime);
            var norm = gEnd - gStart;

            var manualSpan = ev.AllDay
                ? norm
                : (ev.EndTime.TimeOfDay - ev.StartTime.TimeOfDay);

            if (!ev.IsAutoGenerated && manualSpan >= norm)
            {
                return;
            }
            var autoGen = new AutomaticEventsGeneratorService(
                this, 
                _ => Task.FromResult(false) 
            );
            foreach (var d in affectedDates)
            {
                autoGen.RegenerateDailyEventsAsync(d).Wait();
            }
        }


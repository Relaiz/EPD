        public async Task BalanceEventsForMonthAsync(int year, int month, Func<string, Task<bool>> askCollision)
        {
            Log.Info($"Balance START for {month:D2}-{year:D4}");
            if (month < 1 || month > 12)
            {
                var normalized = new DateTime(year, 1, 1).AddMonths(month - 1);
                year = normalized.Year;
                month = normalized.Month;
            }
            var first = new DateTime(year, month, 1);
            var last = new DateTime(year, month, DateTime.DaysInMonth(year, month));
            var days = Enumerable.Range(0, (last - first).Days + 1)
                .Select(i => first.AddDays(i))
                .Where(d => d.DayOfWeek is not DayOfWeek.Saturday and not DayOfWeek.Sunday && !HolidayHelper.IsCzechHoliday(d))
                .ToList();
            Log.Debug($"Workdays: {string.Join(", ", days.Select(d => d.ToString("dd.MM")))}");
            var calc = new WorkingHoursCalculatorService();

            static List<(DateTime s, DateTime e)> MergeIv(IEnumerable<(DateTime s, DateTime e)> iv)
            {
                var list = iv.Where(x => x.e > x.s).OrderBy(x => x.s).ToList();
                var res = new List<(DateTime s, DateTime e)>();
                foreach (var seg in list)
                {
                    if (res.Count == 0 || res[^1].e < seg.s) res.Add(seg);
                    else res[^1] = (res[^1].s, res[^1].e > seg.e ? res[^1].e : seg.e);
                }
                return res;
            }

            (TimeSpan arr, TimeSpan dep, TimeSpan ls, TimeSpan le) GetWindow(DateTime day)
            {
                var sem = GlobalSettingsService.GetSemesterForDate(day);
                var gl = GlobalSettingsService.LoadGlobalSettings(day.Year, sem)
                          ?? GlobalSettingsService.GetDefaultSettings(day.Year, sem);
                var def = PdfService.GetWeekdayDefaults(gl, day.DayOfWeek);
                var us = SettingsService.GetUserSettingsForDate(day);
                return us is null ? def : (us.ArrivalTime, us.DepartureTime, us.LunchStart, us.LunchEnd);
            }

            List<(DateTime s, DateTime e)> FreeGaps(DateTime day)
            {
                var (arr, dep, _, _) = GetWindow(day);
                var winS = day + arr; var winE = day + dep;
                var evs = GetEventsForDay(day);
                var busy = evs.Where(e => e.EventType != EventType.Lunch)
                              .Select(e => (s: e.StartTime < winS ? winS : e.StartTime,
                                            e: e.EndTime > winE ? winE : e.EndTime))
                              .Where(x => x.e > x.s);
                var merged = MergeIv(busy);
                var gaps = new List<(DateTime s, DateTime e)>();
                var cur = winS;
                foreach (var b in merged)
                {
                    if (b.s > cur) gaps.Add((cur, b.s));
                    if (b.e > cur) cur = b.e;
                }
                if (cur < winE) gaps.Add((cur, winE));
                return gaps;
            }

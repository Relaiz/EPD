        private double TrimAutoFromEnd(DateTime day, double hoursToCut)
        {
            if (hoursToCut <= 1e-6) return 0;

            var evs = GetEventsForDay(day)
                .Where(e => !e.IsDeleted && e.EventType != EventType.Lunch)
                .OrderBy(e => e.EndTime)
                .ToList();

            var last = evs.LastOrDefault();
            if (!(last?.IsAutoGenerated == true && last.EventType == EventType.Work))
            {
                return 0;
            }

            double left = hoursToCut;
            using (var db = new AppDbContext())
            {
                while (left > 1e-6)
                {
                    var lastAuto = db.Events
                        .Where(e => !e.IsDeleted
                                 && e.StartTime.Date == day.Date
                                 && e.EventType == EventType.Work
                                 && e.IsAutoGenerated)
                        .OrderByDescending(e => e.EndTime)
                        .FirstOrDefault();

                    if (lastAuto == null) { break; }

                    var len = (lastAuto.EndTime - lastAuto.StartTime).TotalHours;
                    if (len <= 1e-6) { lastAuto.IsDeleted = true; db.SaveChanges(); continue; }

                    var take = Math.Min(len, left);
                    lastAuto.EndTime = lastAuto.EndTime - TimeSpan.FromHours(take);

                    if (lastAuto.EndTime <= lastAuto.StartTime) lastAuto.IsDeleted = true;

                    db.SaveChanges();
                    left -= take;

                    var newLast = db.Events
                        .Where(e => !e.IsDeleted
                                 && e.StartTime.Date == day.Date
                                 && e.EventType != EventType.Lunch)
                        .OrderByDescending(e => e.EndTime)
                        .FirstOrDefault();

                    if (!(newLast?.IsAutoGenerated == true && newLast.EventType == EventType.Work))
                        break;
                }
            }

            var cut = hoursToCut - left;

            if (cut > 1e-6)
            {
                var sem = GlobalSettingsService.GetSemesterForDate(day);
                var gl = GlobalSettingsService.LoadGlobalSettings(day.Year, sem)
                         ?? GlobalSettingsService.GetDefaultSettings(day.Year, sem);
                var (defArr, defDep, defLs, defLe) = PdfService.GetWeekdayDefaults(gl, day.DayOfWeek);
                var us = SettingsService.GetUserSettingsForDate(day);
                var arr = us?.ArrivalTime ?? defArr;

                var lastEnd = GetEventsForDay(day)
                    .Where(e => !e.IsDeleted && e.EventType != EventType.Lunch)
                    .Select(e => e.EndTime)
                    .DefaultIfEmpty(day + arr)
                    .Max()
                    .TimeOfDay;

                var dep = lastEnd;

                var (ls, le) = RefitLunch(day, arr, dep, us?.LunchStart ?? defLs, us?.LunchEnd ?? defLe, (defLe > defLs ? defLe - defLs : TimeSpan.FromMinutes(30)));

                SettingsService.SaveUserSettingsForDate(day, arr, dep, ls, le);
                ReplaceLunchEvent(day, ls, le);
            }

            return cut;
        }




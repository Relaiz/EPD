            async Task<double> CutFromDonor(DateTime day, double maxNeed)
            {
                Log.Debug($"CutFromDonor enter: day={day:dd.MM}, maxNeed={maxNeed:0.##}");
                if (maxNeed <= 1e-6) return 0;

                var all = GetEventsForDay(day);
                var dm = calc.DailyMetrics(day, all);

                var canGive = Math.Max(0, (dm.specialNonPc + dm.workInclBT) - 8.0);
                Log.Debug($"Day {day:dd.MM}: canGive={canGive:0.###}");

                if (canGive <= 1e-6) return 0;
                var taken = await TrimDonorFromEndByUnionAsync(day, Math.Min(canGive, maxNeed));
                if (taken > 1e-6) return taken;
                var toCut = Math.Min(canGive, maxNeed);

                var (arr, dep, ls, le) = GetWindow(day);

                var lastWork = all.Where(e => (e.EventType == EventType.Work || e.EventType == EventType.BusinessTrip) && !e.IsDeleted).OrderByDescending(e => e.EndTime).FirstOrDefault();
                if (lastWork != null)
                    Log.Debug($"Try trim last block: '{lastWork.Title}' {lastWork.StartTime:HH:mm}-{lastWork.EndTime:HH:mm}");

                if (lastWork != null)
                {
                    var maxCutFromBlock = Math.Max(0, (lastWork.EndTime - lastWork.StartTime).TotalHours);
                    var realCut = Math.Min(toCut, maxCutFromBlock);

                    if (realCut > 1e-6)
                    {
                        var cutTs = TimeSpan.FromHours(realCut);
                        var newEnd = lastWork.EndTime - cutTs;
                        Log.Info($"Trimmed {realCut:0.##}h from {day:dd.MM} block -> newEnd={newEnd:HH:mm}");

                        if (newEnd < lastWork.StartTime) newEnd = lastWork.StartTime;

                        lastWork.EndTime = newEnd;
                        UpdateSingleEventEnd(lastWork.Id, newEnd);

                        var us = SettingsService.GetUserSettingsForDate(day);
                        var curArr = us?.ArrivalTime ?? arr;
                        var curDep = us?.DepartureTime ?? dep;
                        var lastManualEndAfterTrim = GetEventsForDay(day)
                        .Where(e => !e.IsAutoGenerated && e.EventType != EventType.Lunch)
                        .Select(e => e.EndTime)
                        .DefaultIfEmpty(day + curArr)
                        .Max()
                        .TimeOfDay;

                        var newDepT = curDep > lastManualEndAfterTrim ? lastManualEndAfterTrim : curDep;

                        var newLs = us?.LunchStart ?? ls;
                        var newLe = us?.LunchEnd ?? le;
                        if (newLe > newLs && (newLe > newDepT || newLs < curArr))
                            (newLs, newLe) = (TimeSpan.Zero, TimeSpan.Zero);

                        SettingsService.SaveUserSettingsForDate(day, curArr, newDepT, newLs, newLe);
                        var us2 = SettingsService.GetUserSettingsForDate(day);
                        ReplaceLunchEvent(day, us2?.LunchStart ?? TimeSpan.Zero, us2?.LunchEnd ?? TimeSpan.Zero);
                        await RebuildDay(day);
                        return realCut;
                    }
                }

                var lastManualEnd = all
                    .Where(e => !e.IsAutoGenerated && e.EventType != EventType.Lunch)
                    .Select(e => e.EndTime)
                    .DefaultIfEmpty(day + arr)
                    .Max();

                var maxCutByWindow = (dep - lastManualEnd.TimeOfDay).TotalHours;
                var realCutByDep = Math.Max(0, Math.Min(toCut, maxCutByWindow));
                if (realCutByDep <= 1e-6) return 0;

                var newDep2 = dep - TimeSpan.FromHours(realCutByDep);
                Log.Debug($"Fallback by dep: lastManualEnd={lastManualEnd:HH:mm}, dep={dep}, maxCutByWindow={maxCutByWindow:0.##}, realCutByDep={realCutByDep:0.##}");
                Log.Info($"Cut by dep {realCutByDep:0.##}h on {day:dd.MM}, newDep={newDep2}");

                TimeSpan newLs2 = ls, newLe2 = le;
                if (newLe2 > newLs2 && (newLe2 > newDep2 || newLs2 < arr))
                    (newLs2, newLe2) = (TimeSpan.Zero, TimeSpan.Zero);

                SettingsService.SaveUserSettingsForDate(day, arr, newDep2, newLs2, newLe2);
                var us3 = SettingsService.GetUserSettingsForDate(day);
                ReplaceLunchEvent(day, us3?.LunchStart ?? TimeSpan.Zero, us3?.LunchEnd ?? TimeSpan.Zero);
                await RebuildDay(day);
                Log.Debug($"CutFromDonor exit: returned={realCutByDep:0.##}");
                return realCutByDep;
            }

                .GroupBy(e => new { e.ImportBatchId, e.ImportLabel })
                .Select(g => new
                {
                    Id = g.Key.ImportBatchId!,
                    Label = g.Key.ImportLabel,
                    RangeStart = g.Min(e => e.StartTime),
                    RangeEnd = g.Max(e => e.EndTime),
                    EventsCount = g.Count()
                })
                .OrderByDescending(x => x.RangeStart)
                .AsNoTracking()
                .ToList();

            return rows
                .Select(x => new ImportBatchInfo(
                    x.Id,
                    x.Label ?? "Načtení",
                    x.RangeStart.Date,
                    x.RangeEnd.Date,
                    x.EventsCount))
                .ToList();
        }

        private List<(DateTime s, DateTime e)> GetBusyIntervals(DateTime day, TimeSpan arr, TimeSpan dep)
        {
            var winS = day + arr;
            var winE = day + dep;
            return GetEventsForDay(day)
                .Where(e => !e.IsDeleted && e.EventType != EventType.Lunch)
                .Select(e => (s: e.StartTime < winS ? winS : e.StartTime,
                              e: e.EndTime > winE ? winE : e.EndTime))
                .Where(x => x.e > x.s)
                .OrderBy(x => x.s)
                .ToList();
        }


        private (TimeSpan ls, TimeSpan le) RefitLunch(DateTime day, TimeSpan arr, TimeSpan dep,
                                                      TimeSpan desiredLs, TimeSpan desiredLe,
                                                      TimeSpan fallbackLen)
        {
            var len = desiredLe > desiredLs ? (desiredLe - desiredLs) : fallbackLen;
            if (dep <= arr || len <= TimeSpan.Zero) return (TimeSpan.Zero, TimeSpan.Zero);

            var busy = GetBusyIntervals(day, arr, dep);

            bool Fits(DateTime s, DateTime e)
                => !busy.Any(iv => !(e <= iv.s || s >= iv.e));

            var c1e = day + dep;
            var c1s = c1e - len;
            if (c1s >= day + arr && Fits(c1s, c1e))
                return (c1s.TimeOfDay, c1e.TimeOfDay);

            var c2s = day + arr;
            var c2e = c2s + len;
            if (c2e <= day + dep && Fits(c2s, c2e))
                return (c2s.TimeOfDay, c2e.TimeOfDay);

            DateTime cursor = day + arr;
            foreach (var iv in busy)
            {
                if (iv.s > cursor && (iv.s - cursor) >= len)
                    return (cursor.TimeOfDay, (cursor + len).TimeOfDay);
                if (iv.e > cursor) cursor = iv.e;
            }
            if (day + dep > cursor && (day + dep - cursor) >= len)
                return (cursor.TimeOfDay, (cursor + len).TimeOfDay);

            return (TimeSpan.Zero, TimeSpan.Zero);
        }

        private double ExtendDayWithAuto(DateTime day, double hours)
        {
            if (hours <= 1e-6) return 0;

            var evs = GetEventsForDay(day).Where(e => !e.IsDeleted && e.EventType != EventType.Lunch)
                                          .OrderBy(e => e.StartTime).ToList();

            var sem = GlobalSettingsService.GetSemesterForDate(day);
            var gl = GlobalSettingsService.LoadGlobalSettings(day.Year, sem)
                      ?? GlobalSettingsService.GetDefaultSettings(day.Year, sem);
            var us = SettingsService.GetUserSettingsForDate(day);
            var (defArr, defDep, defLs, defLe) = PdfService.GetWeekdayDefaults(gl, day.DayOfWeek);

            var arr = us?.ArrivalTime ?? defArr;
            var dep = us?.DepartureTime ?? defDep;

            var lastEnd = evs.Any() ? evs.Last().EndTime : (day + dep);
            var segS = lastEnd;
            var segE = lastEnd.AddHours(hours);

            CreateAutoEvent(new Event
            {
                Title = "Vyvažování práce",
                EventType = EventType.Work,
                StartTime = segS,
                EndTime = segE,
                IsAutoGenerated = true,
                AutoGeneratedForDate = day
            });

            var newDep = segE.TimeOfDay;

            var (nls, nle) = RefitLunch(day, arr, newDep,
                                        us?.LunchStart ?? defLs, us?.LunchEnd ?? defLe,
                                        (defLe > defLs ? defLe - defLs : TimeSpan.FromMinutes(30)));

            if (nle <= nls)
            {
                var desiredLen = (defLe > defLs ? defLe - defLs : TimeSpan.FromMinutes(30));
                if (TryCarveLunchFromInnerAuto(day, arr, newDep, desiredLen, out var cls, out var cle))
                {
                    nls = cls; nle = cle;
                }
            }

            SettingsService.SaveUserSettingsForDate(day, arr, newDep, nls, nle);

            ReplaceLunchEvent(day, nls, nle);
            return hours;
        }

        private bool TryCarveLunchFromInnerAuto(DateTime day,
                                        TimeSpan arr,
                                        TimeSpan dep,
                                        TimeSpan len,
                                        out TimeSpan ls,
                                        out TimeSpan le)
        {
            ls = le = TimeSpan.Zero;
            if (dep <= arr || len <= TimeSpan.Zero) return false;

            var all = GetEventsForDay(day)
                .Where(e => !e.IsDeleted && e.EventType != EventType.Lunch)
                .OrderBy(e => e.StartTime)
                .ToList();

            if (all.Count < 3) return false; 

           
            var candidate = all
                .Skip(1).Take(all.Count - 2) 
                .FirstOrDefault(e =>
                    e.IsAutoGenerated &&
                    e.EventType == EventType.Work &&
                    (e.EndTime - e.StartTime) >= len + TimeSpan.FromMinutes(1) &&
                    e.StartTime >= day + arr &&
                    e.EndTime <= day + dep);

            if (candidate == null) return false;

            var cutStart = candidate.StartTime;
            var cutEnd = candidate.StartTime + len; 

           
            var idx = all.FindIndex(x => x.Id == candidate.Id);
            if (idx <= 0 || idx >= all.Count - 1) return false;
            var prevEnd = all[idx - 1].EndTime;
            var nextStart = all[idx + 1].StartTime;
            if (cutStart < prevEnd || cutEnd > nextStart) return false; 

            using (var db = new AppDbContext())
            {
                var ev = db.Events.Single(x => x.Id == candidate.Id && !x.IsDeleted);
                ev.StartTime = cutEnd;
                if (ev.EndTime < ev.StartTime) ev.EndTime = ev.StartTime; 
                db.SaveChanges();
            }

            CreateAutoEvent(new Event
            {
                Title = "Oběd (auto)",
                EventType = EventType.Lunch,
                StartTime = cutStart,
                EndTime = cutEnd,
                IsAutoGenerated = true,
                AutoGeneratedForDate = day
            });

            ls = cutStart.TimeOfDay;
            le = cutEnd.TimeOfDay;
            return true;
        }
        private async Task BalanceOneWeekAsync(List<DateTime> weekDays)
        {
            const double EPS = 1e-6;
            var calc = new WorkingHoursCalculatorService();

            var metrics = weekDays.Select(d =>
            {
                var m = calc.DailyMetrics(d, GetEventsForDay(d));
                var total = m.specialNonPc + m.workInclBT;
                return new
                {
                    Day = d,
                    Need = Math.Max(0, 8.0 - total),   
                    Extra = Math.Max(0, total - 8.0),  
                    Total = total
                };
            }).ToList();

           
            var deficits = new Queue<(DateTime day, double need)>(
                metrics.Where(x => x.Need > EPS).Select(x => (x.Day, x.Need)));

            var excesses = new Queue<(DateTime day, double extra)>(
                metrics.Where(x => x.Extra > EPS).Select(x => (x.Day, x.Extra)));

            bool IsFlex(DateTime d) => (CanTrimStart(d) || CanTrimEnd(d));
            var flexDays = new Queue<DateTime>(
                metrics.Where(x => x.Need <= EPS && x.Extra <= EPS)
                       .Select(x => x.Day)
                       .Where(IsFlex));

            while (deficits.Count > 0 && excesses.Count > 0)
            {
                var (defDay, need) = deficits.Dequeue();
                var (exDay, extra) = excesses.Dequeue();

                var transfer = Math.Min(need, extra);

                double taken = 0;
                if (CanTrimEnd(exDay)) taken += TrimEndAuto(exDay, transfer - taken);
                if (taken < transfer && CanTrimStart(exDay))
                    taken += TrimStartAuto(exDay, transfer - taken);

                if (taken > EPS)
                {
                    double placed = 0;
                    if (placed < taken) placed += ExtendEndAuto(defDay, taken - placed);
                    if (placed < taken) placed += ExtendStartAuto(defDay, taken - placed);

                    var gen = new AutomaticEventsGeneratorService(this, _ => Task.FromResult(false));
                    await gen.RegenerateDailyEventsAsync(exDay);
                    await gen.RegenerateDailyEventsAsync(defDay);

                    need = Math.Max(0, need - placed);
                    extra = Math.Max(0, extra - taken);
                }

                if (need > EPS) deficits.Enqueue((defDay, need));
                if (extra > EPS) excesses.Enqueue((exDay, extra));
            }

          
            while (excesses.Count > 0 && flexDays.Count > 0)
            {
                var (exDay, extra) = excesses.Dequeue();
                if (extra <= EPS) continue;

                var flexDay = flexDays.Dequeue();

                double taken = 0;
                if (CanTrimEnd(exDay)) taken += TrimEndAuto(exDay, extra - taken);
                if (extra - taken > EPS && CanTrimStart(exDay))
                    taken += TrimStartAuto(exDay, extra - taken);

                double placed = 0;
                if (taken > EPS)
                {
                    if (CanTrimEnd(flexDay))
                        placed += ExtendEndAuto(flexDay, taken - placed);
                    if ((taken - placed) > EPS && CanTrimStart(flexDay))
                        placed += ExtendStartAuto(flexDay, taken - placed);

                    var gen = new AutomaticEventsGeneratorService(this, _ => Task.FromResult(false));
                    await gen.RegenerateDailyEventsAsync(exDay);
                    await gen.RegenerateDailyEventsAsync(flexDay);

                    extra = Math.Max(0, extra - taken);
                }

                if (extra > EPS) excesses.Enqueue((exDay, extra));

                if (placed > EPS) flexDays.Enqueue(flexDay);          
            }
        }


        private async Task BalanceTwoWeeksAsync(List<DateTime> w1, List<DateTime> w2)

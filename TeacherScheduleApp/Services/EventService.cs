        public void DeleteEventCascadeAndCleanup(int id)
        {
            using var db = new AppDbContext();

            var toDelete = db.Events
                .Where(e => e.Id == id || e.ParentEventId == id)
                .ToList();

            if (toDelete.Count == 0) return;


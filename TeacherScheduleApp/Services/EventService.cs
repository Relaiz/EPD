        public void UpdateEvent(Event ev, bool suppressRegen = false)
        {
            using var db = new AppDbContext();
            var parent = db.Events.SingleOrDefault(x => x.Id == ev.Id);
            if (parent == null)
                return;

            var oldEndDate = parent.EndTime.Date;
            parent.Title = ev.Title;
            parent.StartTime = ev.StartTime;
            parent.EndTime = ev.EndTime;
            parent.AllDay = ev.AllDay;
            parent.Description = ev.Description;
            parent.IsDeleted = ev.IsDeleted;
            parent.EventType = ev.EventType;
            parent.ArrivalTime = ev.ArrivalTime;
            parent.DepartureTime = ev.DepartureTime;
            parent.LunchStart = ev.LunchStart;
            parent.LunchEnd = ev.LunchEnd;
            parent.IsAutoGenerated = ev.IsAutoGenerated;
            parent.HasCollision = ev.HasCollision;
            parent.AutoGeneratedForDate = ev.AutoGeneratedForDate;
            db.SaveChanges();

            var oldChildren = db.Events.Where(c => c.ParentEventId == parent.Id).ToList();
            if (oldChildren.Any())
            {
                db.Events.RemoveRange(oldChildren);
                db.SaveChanges();
            }

            DateTime start = parent.StartTime.Date.AddDays(1);
            for (var day = start; day <= ev.EndTime.Date; day = day.AddDays(1))
            {
                if (day.DayOfWeek is DayOfWeek.Saturday or DayOfWeek.Sunday || HolidayHelper.IsCzechHoliday(day))
                    continue;

                var child = new Event
                {
                    Title = parent.Title,
                    Description = parent.Description,
                    EventType = parent.EventType,
                    AllDay = parent.AllDay,
                    StartTime = day + parent.StartTime.TimeOfDay,
                    EndTime = day + parent.EndTime.TimeOfDay,
                    ArrivalTime = day + parent.ArrivalTime.TimeOfDay,
                    DepartureTime = day + parent.DepartureTime.TimeOfDay,
                    LunchStart = day + parent.LunchStart.TimeOfDay,
                    LunchEnd = day + parent.LunchEnd.TimeOfDay,
                    ParentEventId = parent.Id,
                    IsAutoGenerated = parent.IsAutoGenerated
                };
                db.Events.Add(child);
            }
            db.SaveChanges();
            InvalidateMonthsForDates(new[] { parent.StartTime.Date, parent.EndTime.Date });

            if (!suppressRegen)
            {
                var dayToRegen = parent.StartTime.Date;
                AdjustUserSettingsAfterChange(dayToRegen);
                var gen = new AutomaticEventsGeneratorService(this, _ => Task.FromResult(false));
                gen.RegenerateDailyEventsAsync(dayToRegen, preserveUserSettings: true).GetAwaiter().GetResult();
                EnsureLunchInsideWorkWindowAsync(dayToRegen).GetAwaiter().GetResult();
                BalanceWeekForDateAsync(parent.StartTime).GetAwaiter().GetResult();
                MessageBus.Current.SendMessage(new AutoEventsGeneratedMessage());
                MessageBus.Current.SendMessage(new UserSettingsChangedMessage(dayToRegen));
            }
        }


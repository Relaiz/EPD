        private List<(DateTime start, DateTime end)> MergeIntervals(IEnumerable<(DateTime start, DateTime end)> intervals)
        {
            var sorted = intervals.OrderBy(x => x.start).ToList();
            var merged = new List<(DateTime start, DateTime end)>();
            foreach (var seg in sorted)
            {
                if (!merged.Any() || merged.Last().end < seg.start)
                    merged.Add(seg);
                else
                    merged[^1] = (
                        merged.Last().start,
                        merged.Last().end > seg.end ? merged.Last().end : seg.end
                    );
            }
            return merged;
        }

        private (DateTime start, DateTime end) FindGap(DayStat stat, double hours, TimeSpan globalStart, TimeSpan globalEnd)
        {
            var occupied = stat.Events
                .Select(e => (e.StartTime, e.EndTime))
                .OrderBy(iv => iv.StartTime)
                .ToList();

            DateTime cursor = stat.Date + globalStart;
            DateTime windowEnd = stat.Date + globalEnd;

            foreach (var iv in occupied)
            {
                if ((iv.StartTime - cursor).TotalHours >= hours)
                    return (cursor, cursor.AddHours(hours));

                if (iv.EndTime > cursor)
                    cursor = iv.EndTime;
            }

            if ((windowEnd - cursor).TotalHours >= hours)
                return (cursor, cursor.AddHours(hours));

            throw new InvalidOperationException(
                $"Žádné volné místo na {hours:F2}h v {stat.Date:yyyy-MM-dd}");
        }
        private async Task<double> TrimDonorFromEndByUnionAsync(DateTime day, double hoursToCut)
        {
            if (hoursToCut <= 1e-6) return 0;

            var all = GetEventsForDay(day);
            var (arr, dep, _, _) = new AutomaticEventsGeneratorService(this, _ => Task.FromResult(false)).GetType()
                .GetMethod("GetWindow", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance) is { } ? (TimeSpan.Zero, TimeSpan.Zero, TimeSpan.Zero, TimeSpan.Zero) : (TimeSpan.Zero, TimeSpan.Zero, TimeSpan.Zero, TimeSpan.Zero);
            var sem = GlobalSettingsService.GetSemesterForDate(day);
            var gl = GlobalSettingsService.LoadGlobalSettings(day.Year, sem)
                      ?? GlobalSettingsService.GetDefaultSettings(day.Year, sem);
            var def = PdfService.GetWeekdayDefaults(gl, day.DayOfWeek);
            var us = SettingsService.GetUserSettingsForDate(day);
            var winS = day + (us?.ArrivalTime ?? def.arrival);
            var winE = day + (us?.DepartureTime ?? def.departure);

            var workLike = all.Where(e => (e.EventType == EventType.Work || e.EventType == EventType.BusinessTrip) && !e.IsDeleted);
            var merged = BuildMergedWithOwners(workLike, winS, winE);
            if (merged.Count == 0) return 0;

            double cutLeft = hoursToCut;

            for (int i = merged.Count - 1; i >= 0 && cutLeft > 1e-6; i--)
            {
                var segS = merged[i].s;
                var segE = merged[i].e;
                var owners = merged[i].owners.Distinct().OrderByDescending(ev => ev.EndTime).ToList();

                double segLenH = (segE - segS).TotalHours;
                double take = Math.Min(segLenH, cutLeft);

                DateTime newEndLimit = segE.AddHours(-take);
                foreach (var ev in owners)
                {
                    if (ev.EndTime <= newEndLimit) continue;
                    var newEnd = newEndLimit > ev.StartTime ? newEndLimit : ev.StartTime;
                    if (newEnd < ev.EndTime)
                        UpdateSingleEventEnd(ev.Id, newEnd);
                }

                cutLeft -= take;
            }

            var cutDone = hoursToCut - cutLeft;

            if (cutDone > 1e-6)
            {
                var us2 = SettingsService.GetUserSettingsForDate(day);
                var depT = (us2?.DepartureTime ?? def.departure) - TimeSpan.FromHours(cutDone);
                if (depT < (us2?.ArrivalTime ?? def.arrival)) depT = (us2?.ArrivalTime ?? def.arrival);

                TimeSpan ls = us2?.LunchStart ?? def.lunchStart;
                TimeSpan le = us2?.LunchEnd ?? def.lunchEnd;
                if (le > ls && (le > depT || ls < (us2?.ArrivalTime ?? def.arrival)))
                    (ls, le) = (TimeSpan.Zero, TimeSpan.Zero);

                SettingsService.SaveUserSettingsForDate(day, us2?.ArrivalTime ?? def.arrival, depT, ls, le);
                ReplaceLunchEvent(day, ls, le);

                var gen = new AutomaticEventsGeneratorService(this, _ => Task.FromResult(false));
                await gen.RegenerateDailyEventsAsync(day);
            }

            return cutDone;
        }

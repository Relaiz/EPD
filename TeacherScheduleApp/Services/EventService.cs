            async Task<double> PlaceToRecipient(DateTime day, double amount)
            {
                Log.Debug($"PlaceToRecipient enter: day={day:dd.MM}, amount={amount:0.##}");
                if (amount <= 1e-6) return 0;
                double placed = 0;
                var (arr, dep, ls, le) = GetWindow(day);

                DateTime lunchS = day + ls, lunchE = day + le;

                List<(DateTime s, DateTime e)> gaps()
                {
                    var (a, d, _, _) = GetWindow(day);
                    var winS = day + a; var winE = day + d;
                    var evs = GetEventsForDay(day);
                    var busy = evs.Where(e => e.EventType != EventType.Lunch).Select(e => (s: e.StartTime < winS ? winS : e.StartTime, e: e.EndTime > winE ? winE : e.EndTime))
                    .Where(x => x.e > x.s)
                    .OrderBy(x => x.s)
                    .ToList();

                    var merged = new List<(DateTime s, DateTime e)>();
                    foreach (var b in busy)
                    {
                        if (merged.Count == 0 || merged[^1].e < b.s) merged.Add(b);
                        else merged[^1] = (merged[^1].s, merged[^1].e > b.e ? merged[^1].e : b.e);
                    }

                    var gaps = new List<(DateTime s, DateTime e)>();
                    var cur = winS;
                    foreach (var b in merged)
                    {
                        if (b.s > cur) gaps.Add((cur, b.s));
                        if (b.e > cur) cur = b.e;
                    }
                    if (cur < winE) gaps.Add((cur, winE));
                    return gaps;
                }

                async Task ensureLunchOutside(DateTime segS, DateTime segE)
                {
                    bool overlaps = (le > ls) && !(segE <= lunchS || lunchE <= segS);
                    if (!overlaps) { Log.Debug("Lunch OK, no overlap."); return; }
                    Log.Warn($"Lunch overlap on {day:dd.MM} with {segS:HH:mm}-{segE:HH:mm}");
                    if (!lunchState.State.HasValue)
                        lunchState.State = await askCollision("Nový blok práce koliduje s obědem. Posunout oběd za blok pro všechny takové případy?");

                    if (lunchState.State!.Value)
                    {
                        var newLs = segE.TimeOfDay;
                        var newLe = newLs + (le - ls);

                        var newArr = SettingsService.GetUserSettingsForDate(day)?.ArrivalTime ?? arr;
                        var newDep = SettingsService.GetUserSettingsForDate(day)?.DepartureTime ?? dep;
                        Log.Info(lunchState.State!.Value
                        ? $"Lunch moved to after block: {newLs:hh\\:mm}-{newLe:hh\\:mm}"
                        : "Lunch removed for the day");
                        if (day + newLe > day + newDep)
                            SettingsService.SaveUserSettingsForDate(day, newArr, newDep, TimeSpan.Zero, TimeSpan.Zero);
                        else
                            SettingsService.SaveUserSettingsForDate(day, newArr, newDep, newLs, newLe);
                        var us2 = SettingsService.GetUserSettingsForDate(day);
                        ReplaceLunchEvent(day, us2?.LunchStart ?? TimeSpan.Zero, us2?.LunchEnd ?? TimeSpan.Zero);
                        var us = SettingsService.GetUserSettingsForDate(day);
                        lunchS = day + (us?.LunchStart ?? TimeSpan.Zero);
                        lunchE = day + (us?.LunchEnd ?? TimeSpan.Zero);
                    }
                    else
                    {
                        var newArr = SettingsService.GetUserSettingsForDate(day)?.ArrivalTime ?? arr;
                        var newDep = SettingsService.GetUserSettingsForDate(day)?.DepartureTime ?? dep;
                        SettingsService.SaveUserSettingsForDate(day, newArr, newDep, TimeSpan.Zero, TimeSpan.Zero);
                        var us2 = SettingsService.GetUserSettingsForDate(day);
                        ReplaceLunchEvent(day, us2?.LunchStart ?? TimeSpan.Zero, us2?.LunchEnd ?? TimeSpan.Zero);
                        lunchS = lunchE = day;
                    }
                }

                foreach (var g in gaps())
                {
                    Log.Debug($"Gap {day:dd.MM} {g.s:HH:mm}-{g.e:HH:mm} free={(g.e - g.s).TotalHours:0.##}h");
                    if (placed >= amount - 1e-6) break;
                    var free = (g.e - g.s).TotalHours;
                    if (free <= 1e-6) continue;

                    var take = Math.Min(free, amount - placed);
                    var segS = g.s;
                    var segE = g.s.AddHours(take);
                    Log.Info($"Place segment {take:0.##}h -> {segS:HH:mm}-{segE:HH:mm} (day {day:dd.MM})");
                    await ensureLunchOutside(segS, segE);

                    CreateAutoEvent(new Event
                    {
                        Title = "Vyvažování práce",
                        EventType = EventType.Work,
                        StartTime = segS,
                        EndTime = segE,
                        IsAutoGenerated = true,
                        AutoGeneratedForDate = day
                    });

                    placed += take;
                }

                if (placed >= amount - 1e-6)
                {
                    await RebuildDay(day);
                    return placed;
                }

                var still = amount - placed;

                var existing = GetEventsForDay(day).Where(e => e.EventType != EventType.Lunch).ToList();
                var lastBusyEnd = existing.Select(e => e.EndTime).DefaultIfEmpty(day + arr).Max();

                if (lastBusyEnd.TimeOfDay <= dep)
                {
                    var newDep = (lastBusyEnd + TimeSpan.FromHours(still)).TimeOfDay;
                    var curUs = SettingsService.GetUserSettingsForDate(day);
                    var newArr = curUs?.ArrivalTime ?? arr;
                    var curLs = curUs?.LunchStart ?? ls;
                    var curLe = curUs?.LunchEnd ?? le;

                    Log.Info($"Extend dep on {day:dd.MM} by {still:0.##}h -> newDep={newDep}");
                    Log.Info($"Extend arr on {day:dd.MM} by {-still:0.##}h -> newArr={newArr}");

                    SettingsService.SaveUserSettingsForDate(day, newArr, newDep, curLs, curLe);

                    var seg2S = lastBusyEnd;
                    var seg2E = lastBusyEnd.AddHours(still);

                    await ensureLunchOutside(seg2S, seg2E);

                    CreateAutoEvent(new Event
                    {
                        Title = "Vyvažování práce",
                        EventType = EventType.Work,
                        StartTime = seg2S,
                        EndTime = seg2E,
                        IsAutoGenerated = true,
                        AutoGeneratedForDate = day
                    });

                    placed += still;
                    await RebuildDay(day);
                    return placed;
                }

                var firstBusyStart = existing.Select(e => e.StartTime).DefaultIfEmpty(day + dep).Min();
                var curArr = SettingsService.GetUserSettingsForDate(day)?.ArrivalTime ?? arr;

                if ((firstBusyStart.TimeOfDay - curArr).TotalHours >= still)
                {
                    var seg3S = firstBusyStart.AddHours(-still);
                    var seg3E = firstBusyStart;

                    var curUs2 = SettingsService.GetUserSettingsForDate(day);
                    var newArr = seg3S.TimeOfDay;
                    var curDep = curUs2?.DepartureTime ?? dep;
                    var curLs2 = curUs2?.LunchStart ?? ls;
                    var curLe2 = curUs2?.LunchEnd ?? le;

                    SettingsService.SaveUserSettingsForDate(day, newArr, curDep, curLs2, curLe2);

                    await ensureLunchOutside(seg3S, seg3E);

                    CreateAutoEvent(new Event
                    {
                        Title = "Vyvažování práce",
                        EventType = EventType.Work,
                        StartTime = seg3S,
                        EndTime = seg3E,
                        IsAutoGenerated = true,
                        AutoGeneratedForDate = day
                    });

                    placed += still;
                    await RebuildDay(day);
                    return placed;
                }

                if (placed > 1e-6) await RebuildDay(day);
                Log.Debug($"PlaceToRecipient exit: placed={placed:0.##}");
                return placed;
            }

            var totals = days.Select(d =>
            {
                var all = GetEventsForDay(d);
                var m = calc.DailyMetrics(d, all);
                return new
                {
                    Day = d,
                    Total = m.specialNonPc + m.workInclBT
                };
            }).ToList();
            foreach (var t in totals)
                Log.Debug($"Day {t.Day:dd.MM}: total={t.Total:0.###}");
            if (!totals.Any(x => x.Total < 8.0 - 1e-6) || !totals.Any(x => x.Total > 8.0 + 1e-6))
            {
                Log.Info("Nothing to balance: no deficits or no excesses.");
                return;
            }
            var deficits = new Queue<(DateTime day, double need)>(totals
                .Where(x => x.Total < 8.0 - 1e-6)
                .Select(x => (x.Day, 8.0 - x.Total)));

            var excesses = new Queue<(DateTime day, double extra)>(totals
                .Where(x => x.Total > 8.0 + 1e-6)
                .Select(x => (x.Day, x.Total - 8.0)));
            var deniedPairs = new HashSet<(DateTime from, DateTime to)>();
            Log.Info($"Initial deficits: {string.Join(", ", deficits.Select(d => $"{d.day:dd.MM}:{d.need:0.##}"))}");
            Log.Info($"Initial excesses: {string.Join(", ", excesses.Select(e => $"{e.day:dd.MM}:{e.extra:0.##}"))}");
            int noProgressTurns = 0;
            int stallLimit = Math.Max(10, deficits.Count * Math.Max(1, excesses.Count) + 10);
            while (deficits.Count > 0 && excesses.Count > 0)
            {
                var (defDay, need) = deficits.Dequeue();
                var (exDay, extra) = excesses.Dequeue();

                Log.Info($"Loop: take from {exDay:dd.MM} extra={extra:0.##} -> put to {defDay:dd.MM} need={need:0.##}");

                var amount = Math.Min(extra, need);
                if (deniedPairs.Contains((exDay.Date, defDay.Date)))
                {
                    if (need > 1e-6) deficits.Enqueue((defDay, need));
                    if (extra > 1e-6) excesses.Enqueue((exDay, extra));
                    if (++noProgressTurns > stallLimit)
                    {
                        Log.Warn("Balance aborted: no progress (all relevant pairs denied).");
                        break;
                    }
                    continue;
                }
                var ok = await ConfirmMoveAsync(exDay, defDay, amount);
                if (!ok)
                {
                    deniedPairs.Add((exDay.Date, defDay.Date));
                    if (need > 1e-6) deficits.Enqueue((defDay, need));
                    if (extra > 1e-6) excesses.Enqueue((exDay, extra));
                    if (++noProgressTurns > stallLimit)
                    {
                        Log.Warn("Balance aborted: no progress (user denied moves).");
                        break;
                    }
                    continue;
                }
                var taken = await CutFromDonor(exDay, amount);
                Log.Info($"CutFromDonor({exDay:dd.MM}, amount={amount:0.##}) => taken={taken:0.##}");
                if (taken <= 1e-6)
                {
                    if (need > 1e-6) deficits.Enqueue((defDay, need));
                    continue;
                }

                var placed = await PlaceToRecipient(defDay, taken);
                Log.Info($"CutFromDonor({exDay:dd.MM}, amount={amount:0.##}) => taken={taken:0.##}");
                var leftNeed = Math.Max(0, need - placed);

                var leftExtra = Math.Max(0, extra - taken);
                Log.Debug($"Left: need={leftNeed:0.##}, extra={leftExtra:0.##}");
                bool progressed = (taken > 1e-6) && (placed > 1e-6);
                noProgressTurns = progressed ? 0 : (noProgressTurns + 1);

                if (placed <= 1e-6)
                {
                    leftExtra = extra;
                    if (need > 1e-6) deficits.Enqueue((defDay, need));
                }

                if (leftNeed > 1e-6) deficits.Enqueue((defDay, leftNeed));
                if (leftExtra > 1e-6) excesses.Enqueue((exDay, leftExtra));
                if (noProgressTurns > stallLimit)
                {
                    Log.Warn("Balance aborted: no progress (stall).");
                    break;
                }
                Log.Info("Balance END");
            }
        }

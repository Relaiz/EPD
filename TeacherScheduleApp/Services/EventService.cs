                    var dep = us?.DepartureTime ?? defDep;
                    var ls = us?.LunchStart ?? defLs;
                    var le = us?.LunchEnd ?? defLe;

                    arr = newStart.TimeOfDay < dep ? newStart.TimeOfDay : dep;

                    if (le > ls && (le > dep || ls < arr))
                    {
                        var len = le - ls;
                        var nle = arr + len;
                        if (nle <= dep)
                            (ls, le) = (arr, nle);
                        else
                            (ls, le) = (TimeSpan.Zero, TimeSpan.Zero);
                    }

                    SettingsService.SaveUserSettingsForDate(day, arr, dep, ls, le);
                    ReplaceLunchEvent(day, ls, le);
                    var gen = new AutomaticEventsGeneratorService(this, _ => Task.FromResult(true));
                    await gen.RegenerateDailyEventsAsync(day);
                }
            }
        }
    }
    static class Log
    {
        private static readonly object _lock = new object();
        private static string _path;
        private static bool _enabled = true;

        public static void Init(string name = "balance")
        {
            try
            {
                var dir = Path.Combine(
                    Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                    "TeacherScheduleApp", "logs");
                Directory.CreateDirectory(dir);
                var ts = DateTime.Now.ToString("yyyyMMdd-HHmmss");
                _path = Path.Combine(dir, $"{name}-{ts}.txt");
                WriteLine($"=== NEW SESSION {DateTime.Now:yyyy-MM-dd HH:mm:ss.fff} ===");
                WriteLine($"PID={Environment.ProcessId}, Thread={Environment.CurrentManagedThreadId}");
            }
            catch { /* ignore */ }
        }

        public static void Enable(bool enabled) => _enabled = enabled;

        public static void WriteLine(string msg)
        {
            if (!_enabled) return;
            lock (_lock)
            {
                try
                {
                    if (string.IsNullOrEmpty(_path)) Init();
                    File.AppendAllText(_path,
                        $"{DateTime.Now:HH:mm:ss.fff} [T{Environment.CurrentManagedThreadId}] {msg}\r\n",
                        Encoding.UTF8);
                }
                catch { }
            }
        }

        public static void Info(string msg) => WriteLine("[INFO]  " + msg);
        public static void Warn(string msg) => WriteLine("[WARN]  " + msg);
        public static void Error(string msg) => WriteLine("[ERROR] " + msg);
        public static void Debug(string msg) => WriteLine("[DEBUG] " + msg);
    }
